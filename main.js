function layoutDots(){
  if(mobileNavQuery.matches){
    ring.style.transform="";
    ring.querySelectorAll(".dot").forEach(b=>{b.style.transform="";});
    return;
  }
  const r=R();
  ring.querySelectorAll(".dot").forEach((b,i)=>{
    const a=i*(360/N);
    b.style.transform=`rotate(${a}deg) translateY(${-r}px) rotate(${-a}deg)`;
  });
}
function buildLabels(){
  ring.querySelectorAll(".dot").forEach((b,i)=>{b.setAttribute("aria-label",I18N[lang].sections[i]);b.title=I18N[lang].sections[i];});
}
function updateWheel(idx,animate=true){
  currentIdx=idx;
  if(mobileNavQuery.matches){
    ring.style.transform="";
    ring.querySelectorAll(".dot").forEach((b,i)=>{
      b.classList.toggle("active",i===idx);
      b.style.transform="";
    });
    document.getElementById("wheelCurrent").textContent=I18N[lang].sections[idx];
    return;
  }
  const rot=-idx*(360/N);
  if(!animate){ring.style.transition="none";requestAnimationFrame(()=>ring.style.transition="");}
  ring.style.transform=`rotate(${rot}deg)`;
  ring.querySelectorAll(".dot").forEach((b,i)=>{
    b.classList.toggle("active",i===idx);
    const a=i*(360/N);
    b.style.transform=`rotate(${a}deg) translateY(${-R()}px) rotate(${-(a+rot)}deg)`;
  });
  document.getElementById("wheelCurrent").textContent=I18N[lang].sections[idx];
}
function goToSection(idx){
  const next=Math.max(0,Math.min(N-1,idx));
  document.getElementById(sectionIds[next]).scrollIntoView({behavior:"smooth"});
}
const hubBtn=document.getElementById("hub");
if(hubBtn) hubBtn.addEventListener("click",()=>{document.getElementById("home").scrollIntoView({behavior:"smooth"});});
if(ring && wheelEl){
wheelEl.addEventListener("touchstart",e=>{touchStartY=e.touches[0].clientY;},{passive:true});
wheelEl.addEventListener("touchend",e=>{
  if(touchStartY===null || !mobileNavQuery.matches) return;
  const endY=e.changedTouches[0].clientY;
  const delta=touchStartY-endY;
  touchStartY=null;
  if(Math.abs(delta)<28) return;
  e.preventDefault();
  goToSection(currentIdx+(delta>0?1:-1));
},{passive:false});

const obs=new IntersectionObserver(es=>{
  es.forEach(e=>{ if(e.isIntersecting) updateWheel(sectionIds.indexOf(e.target.id)); });
},{rootMargin:"-45% 0px -45% 0px"});
sectionIds.forEach(id=>{const el=document.getElementById(id); if(el) obs.observe(el);});

window.addEventListener("resize",()=>{layoutDots();updateWheel(currentIdx,false);});
}

